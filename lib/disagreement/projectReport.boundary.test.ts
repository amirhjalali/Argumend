import { describe, expect, it } from "vitest";
import type { RawDisagreementExtractionV1 } from "@/types/disagreement";
import { parseDisagreementReport, RawDisagreementExtractionSchema } from "@/lib/schemas/disagreement";
import { analyzeDisagreement } from "./analyze";
import { DISAGREEMENT_LIMITS as L } from "./constants";
import { FakeDisagreementProvider } from "./model/fake";
import { DISAGREEMENT_FEW_SHOT_EXAMPLES } from "./prompts/v1/examples";
import { canPublishReport } from "./quality";

const example = DISAGREEMENT_FEW_SHOT_EXAMPLES[0];

async function analyze(extraction: RawDisagreementExtractionV1) {
  expect(RawDisagreementExtractionSchema.safeParse(extraction).success).toBe(true);
  const result = await analyzeDisagreement({
    content: `${example.source}\nBoth participants want reliable health coverage information.`,
    contentType: example.contentType,
    requestId: "report-boundary-test",
    provider: new FakeDisagreementProvider(extraction),
  });
  expect(canPublishReport(result.report).ok).toBe(true);
  expect(parseDisagreementReport(result.report).success).toBe(true);
  return result;
}

describe("generated report text boundaries", () => {
  it("preserves a maximum-length main question without adding punctuation beyond its limit", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.mainQuestion = "a".repeat(L.maxQuestionCharacters);

    const { report } = await analyze(extraction);

    expect(report.question).toBe(extraction.mainQuestion);
    expect(report.title).toBe(extraction.mainQuestion);
  });

  it("keeps a complete maximum-length claim and puts the conditional wording in its consequences", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.claims[0].statement = "a".repeat(L.maxThesisCharacters);

    const { report, graph } = await analyze(extraction);

    const crux = report.cruxes.find((item) => item.claimId === extraction.claims[0].id)!;
    expect(crux.branches.length).toBeGreaterThan(0);
    for (const branch of crux.branches) {
      expect(branch.condition).toBe(extraction.claims[0].statement);
      expect(branch.consequence).toMatch(/^If this holds: /);
    }
    expect(graph.nodes.find((node) => node.id === extraction.claims[0].id)?.statement)
      .toBe(extraction.claims[0].statement);
  });

  it("preserves full position labels while bounding their generated consequences and explanations", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.positions[0].label = "a".repeat(L.maxThesisCharacters);

    const { report } = await analyze(extraction);

    expect(report.positions[0].label).toBe(extraction.positions[0].label);
    expect(report.cruxes.flatMap((crux) => crux.branches).map((branch) => branch.consequence))
      .toContain("The case for one affected position gets stronger.");
    expect(report.cruxes.map((crux) => crux.whyItMatters))
      .toContain("Settling this affects 2 positions; their cases depend on how this claim is resolved.");
  });

  it("keeps model labels out of repair diagnostics without altering the participant label", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.participants[0].label = "a".repeat(L.maxThesisCharacters);
    extraction.participants.push({ ...extraction.participants[0], id: "alias" });

    const { report } = await analyze(extraction);

    expect(report.participants[0].label).toBe(extraction.participants[0].label);
    const warning = report.quality.warnings.find((item) => item.startsWith("Deduplicated participant label"))!;
    expect(warning).toBe("Deduplicated participant label at index 2.");
    expect(warning.length).toBeLessThanOrEqual(L.maxQualityWarningCharacters);
  });

  it("bounds the diagnostics generated by the maximum number of dangling relations", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.claimRelations = Array.from({ length: L.maxClaimRelations }, () => ({
      fromClaimId: "missing", toClaimId: "also-missing", type: "supports" as const,
    }));

    const { report } = await analyze(extraction);

    expect(report.quality.warnings).toHaveLength(L.maxQualityWarnings);
    expect(report.quality.warnings).toContain("Dropped dangling claim relation");
  });

  it("retains a nonempty title when the model question consists only of punctuation", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.mainQuestion = "?";

    const { report } = await analyze(extraction);

    expect(report.title).toBe("?");
    expect(report.question).toBe("?");
  });

  it("preserves a complete claim when the generated fallback question would overflow", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.claims[0].statement = "a".repeat(L.maxThesisCharacters);
    extraction.disagreementCandidates = [];

    const { report } = await analyze(extraction);

    expect(report.cruxes.find((crux) => crux.claimId === extraction.claims[0].id)?.question)
      .toBe(extraction.claims[0].statement);
  });

  it("uses the complete crux question when the generated insight prefix would overflow", async () => {
    const extraction = structuredClone(example.extraction);
    extraction.disagreementCandidates[0].question = "a".repeat(L.maxQuestionCharacters);
    extraction.disagreementCandidates[0].claimIds = extraction.claims.map((claim) => claim.id);

    const { report } = await analyze(extraction);

    expect(report.cruxes[0].question).toBe(extraction.disagreementCandidates[0].question);
    expect(report.summary).toBe(extraction.disagreementCandidates[0].question);
    expect(report.diagnosis.insight).toBe(extraction.disagreementCandidates[0].question);
  });
});
